"""Single-series driver (setting S1, one long series): one ITPD run per series on the last window slice vs a run on every slice.

    python -m itpd.experiments single_series --out-dir DIR [--N 10,20,40 --T 200,1000,10000 --tau 1,2,3 --d 2 --graphs 20 --workers 16]

S1 data: one stationary VAR(tau) trajectory (T, N) generated by recursion (no unrolled graph: T up to 10,000), lag weights
fixed in t (spectral radius <= 0.9), the first `burn` = 100 steps discarded (`sim.simulate_s1` has no burn-in), the
faithfulness guard computed from the exact stationary covariance of the window (partial and marginal correlation of every
edge into the last slice >= 0.02). The base lag graph and weights of a graph index are the same for every T. Instance file
(kind "s1", no unrolled A): B, Wl, T, N, tau, d, seed, data_seed, burn, meta_json, sha1(B); data = `s1_data(inst)`.
Windows: row s of `sim.windows(X, tau)` = V_{s..s+tau}, n = T - tau rows, column l * N + n (slice l); the Fisher-z test uses
n = T - tau as sample size although the rows overlap (dependent samples: a violation of the test's iid assumption).
Methods (alpha = 0.01, Fisher-z, lazy, one memoised test per dataset):
  last-slice: itpd (= itpd_naive by construction: with one pair per series no cross-pair rule can fire) and full_conditioning,
              one PaDL / one test per candidate for each series N at the last slice; truth B (lag graph, self and lag 0 excluded).
  every-slice: PaDL for every series at every window slice 1..tau (S2 on the window, T' = tau + 1, candidates = earlier window
              nodes), itpd_naive and itpd; per target slice k the output is compared with the in-window true parents
              (lags <= k; parents before the window are latent): wrong-target share, precision / recall / F1; `union` = OR of the
              estimates over slices, scored against B.
Rows are named itpd_last_slice, full_conditioning_last_slice, itpd_naive_every_slice, itpd_every_slice (earlier results: itpd_last,
order_last, naive_every, itpd_every; methods_registry.OLD_TO_NEW).
"""
from __future__ import annotations

import argparse
import itertools
import json
import os
import time

import numpy as np
from scipy.linalg import solve_discrete_lyapunov

from .. import sim
from .. import itpd as _itpd
from ..baselines import full_conditioning as _order
from ..ci import FisherZ, InfeasibleTest, Recorder
from ..graphs import unroll
from ..metrics import lag_metrics
from . import common

BURN = 100
ALPHA = 0.01


def _sub(*p):
    return np.random.default_rng(np.random.SeedSequence([int(x) for x in p]))


def window_cov(Wl: np.ndarray) -> np.ndarray:
    """Exact stationary covariance of the window (slice l, node n) = X_{t - tau + l}, as a ((tau+1) N)^2 matrix (unit noise)."""
    tau, N = Wl.shape[0] - 1, Wl.shape[1]
    D = N * (tau + 1)                       # companion state Z_t = (X_t, ..., X_{t-tau})
    C = np.zeros((D, D))
    for l in range(1, tau + 1):
        C[:N, (l - 1) * N:l * N] = Wl[l].T
    C[N:, :-N] = np.eye(N * tau)
    Q = np.zeros((D, D))
    Q[:N, :N] = np.eye(N)
    G = solve_discrete_lyapunov(C, Q)       # block j = X_{t-j}; window slice l = tau - j
    perm = np.concatenate([np.arange((tau - l) * N, (tau - l + 1) * N) for l in range(tau + 1)])
    return G[np.ix_(perm, perm)]


def s1_instance(N, T, tau, d, seed, g, tries=25, min_strength=0.02):
    rng_g = _sub(seed, N, tau, int(round(d * 10)), g, 5)
    B = sim.sample_window_graph(N, tau, d, rng_g)
    rng_w = _sub(seed, N, tau, int(round(d * 10)), g, 6)
    Aw = unroll(B, tau + 1)
    Alast = np.zeros_like(Aw)
    Alast[:, tau * N:] = Aw[:, tau * N:]
    for k in range(1, tries + 1):
        Wl = sim.stable_window_weights(B, rng_w)
        S = window_cov(Wl)
        pm, mm = sim.faithfulness_margin(Alast, S), sim.marginal_margin(Alast, S)
        if min(pm, mm) >= min_strength:
            break
    ds = [int(seed), N, tau, int(round(d * 10)), g, 90210]          # independent of T: longer series extend shorter ones
    return {"B": B, "Wl": Wl, "N": N, "T": T, "tau": tau, "d": d, "seed": seed, "g": g, "data_seed": ds, "burn": BURN,
            "meta": {"min_partial_corr": float(pm), "min_marginal_corr": float(mm), "guard_tries": k,
                     "guard_ok": bool(min(pm, mm) >= min_strength)}}


def gen_series(Wl: np.ndarray, eps: np.ndarray) -> np.ndarray:
    """X_t = sum_l X_{t-l} @ Wl[l] + eps_t, starting at t = 0 with roots (rows of eps are the noise)."""
    tau = Wl.shape[0] - 1
    X = np.zeros_like(eps)
    for t in range(eps.shape[0]):
        x = eps[t].copy()
        for l in range(1, min(tau, t) + 1):
            x += X[t - l] @ Wl[l]
        X[t] = x
    return X


def s1_data(inst: dict) -> np.ndarray:
    """(T, N) series: the first T rows after the burn-in of one trajectory of T_max rows (extends with T)."""
    N, T = inst["N"], inst["T"]
    eps = np.random.default_rng(np.random.SeedSequence(inst["data_seed"])).standard_normal((inst["burn"] + T, N))
    return gen_series(inst["Wl"], eps)[inst["burn"]:]


def save_s1_instance(path, inst):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    B = inst["B"].astype(np.uint8)
    tmp = path + f".tmp{os.getpid()}.npz"
    np.savez_compressed(tmp, B=B, Wl=inst["Wl"].astype(np.float64), N=inst["N"], T=inst["T"], tau=inst["tau"], d=inst["d"],
                        seed=inst["seed"], index=inst["g"], data_seed=np.asarray(inst["data_seed"], dtype=np.int64),
                        burn=inst["burn"], kind="s1", meta_json=json.dumps(inst["meta"]), sha1=
                        __import__("hashlib").sha1(B.tobytes()).hexdigest())
    os.replace(tmp, path)


def load_s1_instance(path):
    z = np.load(path, allow_pickle=False)
    o = {k: z[k] for k in z.files}
    for k in ("N", "T", "tau", "burn", "index"):
        o[k] = int(o[k])
    o["B"] = o["B"].astype(bool)
    o["Wl"] = o["Wl"].astype(float)
    o["data_seed"] = [int(v) for v in o["data_seed"]]
    o["meta"] = json.loads(str(o["meta_json"]))
    return o


def _lag_from_window(A_hat, N, tau):
    B = np.zeros((tau + 1, N, N), dtype=bool)
    for k in range(1, tau + 1):
        for j in range(k):
            blk = A_hat[j * N:(j + 1) * N, k * N:(k + 1) * N] != 0
            B[k - j] |= blk
    return B


def run_one(inst):
    N, tau = inst["N"], inst["tau"]
    X = s1_data(inst)
    W = sim.windows(X, tau)
    n = W.shape[0]
    ci = FisherZ(W)
    shared: dict = {}
    B = inst["B"]
    Aw = unroll(B, tau + 1)
    out = {"n_rows": n, "runs": []}

    def rec_():
        return Recorder(ci, cache="run", infeasible="raise", shared=shared)

    # last slice
    for name, fn in (("itpd_last_slice", lambda r: _itpd.run_s1(r, N, tau, ALPHA, lazy=True)),
                     ("full_conditioning_last_slice", lambda r: _order.run_s1(r, N, tau, ALPHA))):
        r = rec_()
        try:
            res = fn(r)
            m = lag_metrics(B, res.B_hat)
            out["runs"].append({"name": name, "status": "ok", "metrics": m, "unique": res.summary["unique_tests"],
                                "raw": res.summary["raw_calls"], "max_size": max(p["max_size"] for p in res.per_pair),
                                "by_size_unique": res.summary["by_size_unique"]})
        except InfeasibleTest:
            out["runs"].append({"name": name, "status": "infeasible", "unique": r.summary()["unique_tests"]})
    # every slice (S2 on the window, T' = tau + 1)
    for name, reuse in (("itpd_naive_every_slice", False), ("itpd_every_slice", True)):
        r = rec_()
        try:
            res = _itpd.run_s2(r, N, tau + 1, ALPHA, reuse=reuse, lazy=True)
        except InfeasibleTest:
            out["runs"].append({"name": name, "status": "infeasible", "unique": r.summary()["unique_tests"]})
            continue
        per = {}
        for k in range(1, tau + 1):
            cols = slice(k * N, (k + 1) * N)
            t_, h_ = Aw[:, cols].copy(), (res.A_hat[:, cols] != 0).copy()
            for i in range(N):                                   # self edge (lag 1) excluded, as in the headline score
                t_[(k - 1) * N + i, i] = False
                h_[(k - 1) * N + i, i] = False
            tp, fp, fn = int((t_ & h_).sum()), int((~t_ & h_).sum()), int((t_ & ~h_).sum())
            wrong = int(((t_ != h_).any(axis=0)).sum())
            per[k] = {"tp": tp, "fp": fp, "fn": fn, "wrong_targets": wrong, "targets": N}
        Bu = _lag_from_window(res.A_hat, N, tau)
        out["runs"].append({"name": name, "status": "ok", "per_slice": per, "metrics_union": lag_metrics(B, Bu),
                            "unique": res.summary["unique_tests"], "raw": res.summary["raw_calls"]})
    return out


def run_task(a):
    out, N, T, tau, d, seed, g = a
    path = os.path.join(out, f"N{N}_T{T}_tau{tau}_d{d:g}", f"g{g:02d}.json")
    if os.path.exists(path):
        return path, "exists", 0.0
    t0 = time.time()
    inst = s1_instance(N, T, tau, d, seed, g)
    ipath = os.path.join(out, "instances", f"N{N}_T{T}_tau{tau}_d{d:g}_g{g:02d}.npz")
    if not os.path.exists(ipath):
        save_s1_instance(ipath, inst)
    res = run_one(inst)
    res.update({"N": N, "T": T, "tau": tau, "d": d, "seed": seed, "graph": g, "meta": inst["meta"],
                "n_true_edges": int(inst["B"][1:].sum() - N), "seconds": time.time() - t0})
    common.dump_json(path, res)
    return path, "done", time.time() - t0


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--out-dir", required=True)
    ap.add_argument("--N", default="10,20,40")
    ap.add_argument("--T", default="200,1000,10000")
    ap.add_argument("--tau", default="1,2,3")
    ap.add_argument("--d", type=float, default=2.0)
    ap.add_argument("--graphs", type=int, default=20)
    ap.add_argument("--seed", type=int, default=0)
    common.add_pool_args(ap)
    ap.add_argument("--instances-only", action="store_true", help="(re)write the instance files only (overwrites)")
    a = ap.parse_args(argv)
    if a.instances_only:
        for N, T, tau, g in itertools.product(common.ints(a.N), common.ints(a.T), common.ints(a.tau), range(a.graphs)):
            save_s1_instance(os.path.join(a.out_dir, "instances", f"N{N}_T{T}_tau{tau}_d{a.d:g}_g{g:02d}.npz"),
                             s1_instance(N, T, tau, a.d, a.seed, g))
        return
    tasks = [(a.out_dir, N, T, tau, a.d, a.seed, g)
             for N, T, tau, g in itertools.product(common.ints(a.N), common.ints(a.T), common.ints(a.tau), range(a.graphs))]
    ex = lambda t: os.path.exists(os.path.join(t[0], f"N{t[1]}_T{t[2]}_tau{t[3]}_d{t[4]:g}", f"g{t[6]:02d}.json"))
    todo = sorted([t for t in tasks if not ex(t)], key=lambda t: -(t[1] * t[3]) ** 2)
    print(f"tasks {len(tasks)} todo {len(todo)}", flush=True)
    t0 = time.time()
    common.run_tasks(run_task, todo, a.workers, t0 + a.budget_sec)
    common.finish(t0, len([t for t in tasks if not ex(t)]))


if __name__ == "__main__":
    main()
